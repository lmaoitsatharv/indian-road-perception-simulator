function record=traffic_npc_intervention(time,actorIndex,blockingIndex,specs,requestedSpeed,requestedRouteStep,requestedLateralStep)
% Record rejected proposals using stable actor IDs, including the ego ID 0.
% The guard's row index for the appended ego must not masquerade as actor 30.
record=struct('time_s',time,'actor_id',specs(actorIndex).id, ...
    'blocking_actor_id',specs(blockingIndex).id, ...
    'requested_speed_mps',requestedSpeed,'accepted_speed_mps',0, ...
    'requested_route_step_m',requestedRouteStep,'accepted_route_step_m',0, ...
    'requested_lateral_step_m',requestedLateralStep,'accepted_lateral_step_m',0, ...
    'reason','prospective_body_conflict_step_held');
end
