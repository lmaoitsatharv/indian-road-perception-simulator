function data=load_traffic_replay(runDir)
%LOAD_TRAFFIC_REPLAY Validate a saved rollout before creating graphics/timers.
% A replay does not use or renew a batch session deadline or monitor lease.
arguments
    runDir (1,:) char
end
path=fullfile(runDir,'world.mat');
assert(isfile(path),'Tesla:ReplayMissing','Saved scene was not found: %s',path);
required={'config','specs','route','egoLog','actorLog','result'};
data=load(path,required{:});
assert(all(isfield(data,required)),'Tesla:ReplayFormat','The saved scene is missing replay data.');
cfg=data.config;ego=data.egoLog;actors=data.actorLog;specs=data.specs;
assert(isstruct(cfg) && isscalar(cfg) && all(isfield(cfg, ...
    {'seed','vehicle_count','pedestrian_count','loop_length_m'})), ...
    'Tesla:ReplayFormat','The scene configuration is incomplete.');
for field={'seed','vehicle_count','pedestrian_count'}
    v=cfg.(field{1});
    assert(isnumeric(v) && isscalar(v) && isfinite(v) && v>=0 && v==fix(v), ...
        'Tesla:ReplayFormat','Scene counts and seed must be nonnegative finite integers.');
end
assert(isnumeric(cfg.loop_length_m) && isscalar(cfg.loop_length_m) && ...
    isfinite(cfg.loop_length_m) && cfg.loop_length_m>0, ...
    'Tesla:ReplayFormat','The road loop length must be positive and finite.');
assert(isnumeric(ego) && isreal(ego) && ismatrix(ego) && size(ego,1)>=2 && size(ego,2)>=11, ...
    'Tesla:ReplayFormat','Ego log needs at least two samples and eleven columns.');
assert(all(isfinite(ego(:,1:11)),'all') && ego(1,1)==0 && all(diff(ego(:,1))>0), ...
    'Tesla:ReplayFormat','Ego timestamps must start at zero and increase strictly; displayed states must be finite.');
assert(all(ismember(ego(:,10),0:2)) && all(ismember(ego(:,11),0:1)), ...
    'Tesla:ReplayFormat','Ego decision/braking codes are invalid.');
if size(ego,2)>=13
    assert(all(ismember(ego(:,13),0:3)),'Tesla:ReplayFormat','Maneuver codes are invalid.');
end
assert(isstruct(specs) && all(isfield(specs, ...
    {'kind','length_m','width_m','rear_overhang_m','color'})) && ...
    numel(specs)>=cfg.vehicle_count+cfg.pedestrian_count, ...
    'Tesla:ReplayFormat','Actor definitions do not match the scene counts.');
assert(isnumeric(actors) && isreal(actors) && size(actors,1)==size(ego,1) && ...
    size(actors,2)==numel(specs) && size(actors,3)>=6 && ...
    all(isfinite(actors),'all'), ...
    'Tesla:ReplayFormat','Actor logs must contain finite states for every ego timestamp and actor.');
for j=1:numel(specs)
    spec=specs(j);dims=[spec.length_m,spec.width_m,spec.rear_overhang_m];
    assert(ischar(spec.kind) && isrow(spec.kind) && ...
        ismember(spec.kind,{'car','auto_rickshaw','two_wheeler','pedestrian','parked_car'}) && ...
        isnumeric(dims) && numel(dims)==3 && all(isfinite(dims)) && ...
        all(dims(1:2)>0) && dims(3)>=0 && dims(3)<dims(1) && ...
        isnumeric(spec.color) && isequal(size(spec.color),[1,3]) && ...
        all(isfinite(spec.color)) && all(spec.color>=0 & spec.color<=1), ...
        'Tesla:ReplayFormat','An actor shape, kind or colour is invalid.');
end
pedestrianSlots=cfg.vehicle_count+(1:cfg.pedestrian_count);
assert(all(strcmp({specs(pedestrianSlots).kind},'pedestrian')), ...
    'Tesla:ReplayFormat','Pedestrian slots do not match the scene configuration.');
assert(isnumeric(data.route) && size(data.route,2)>=3 && all(isfinite(data.route),'all'), ...
    'Tesla:ReplayFormat','The saved route is invalid.');
assert(isstruct(data.result) && isscalar(data.result) && all(isfield(data.result, ...
    {'ego_collision_samples','non_ego_overlap_samples_at_0_5s'})), ...
    'Tesla:ReplayFormat','Saved run collision counts are missing.');
for field={'ego_collision_samples','non_ego_overlap_samples_at_0_5s'}
    v=data.result.(field{1});
    assert(isnumeric(v) && isscalar(v) && isfinite(v) && v>=0 && v==fix(v), ...
        'Tesla:ReplayFormat','Saved run collision counts must be nonnegative integers.');
end
end
