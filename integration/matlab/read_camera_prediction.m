function frame = read_camera_prediction(frameDir)
%READ_CAMERA_PREDICTION Read Python's 0/1 mask without treating pixels as metres.
arguments
    frameDir (1,:) char
end
metadata = jsondecode(fileread(fullfile(frameDir,'frame.json')));
required={'schema_version','kind','frame','units','threshold','threshold_comparator', ...
    'image_shape_hwc','mask_values','mask_file','metric_projection_available', ...
    'actor_detection_available','planning_map','planning_use_valid'};
assert(isstruct(metadata) && isscalar(metadata) && all(isfield(metadata,required)), ...
    'Tesla:CameraFrameFormat','Camera metadata is incomplete or not a single frame.');
assert(textEquals(metadata.schema_version,'0.1-draft') && ...
    textEquals(metadata.kind,'road_segmentation_camera_frame'), ...
    'Tesla:CameraFrameFormat','Unexpected camera-frame schema/kind.');
assert(textEquals(metadata.frame,'model_image_pixels') && textEquals(metadata.units,'pixels'), ...
    'Tesla:CameraFrameFormat','Unexpected image frame/units.');
assert(isnumeric(metadata.threshold) && isscalar(metadata.threshold) && metadata.threshold==.5 && ...
    textEquals(metadata.threshold_comparator,'>='), ...
    'Tesla:CameraFrameFormat','The final threshold must remain >= 0.5.');
assert(isnumeric(metadata.image_shape_hwc) && isequal(metadata.image_shape_hwc(:)',[512,512,3]) && ...
    isnumeric(metadata.mask_values) && isequal(metadata.mask_values(:)',[0,1]), ...
    'Tesla:CameraFrameFormat','Metadata must describe 512x512 RGB and binary 0/1 labels.');
assert(ischar(metadata.mask_file) && isrow(metadata.mask_file) && ...
    ~isempty(regexp(metadata.mask_file,'^[A-Za-z0-9][A-Za-z0-9_.-]*\.png$','once')), ...
    'Tesla:CameraFrameFormat','mask_file must be a PNG filename within the frame directory.');
% The pixel-frame reader has no metric projection or obstacle observations.
% Contradictory flags are rejected rather than propagated as planning evidence.
assert(isFalse(metadata.metric_projection_available) && isFalse(metadata.actor_detection_available) && ...
    isFalse(metadata.planning_use_valid) && isempty(metadata.planning_map), ...
    'Tesla:CameraPlanningClaim','A camera pixel frame cannot claim a valid metric planning map.');
mask = imread(fullfile(frameDir,metadata.mask_file));
assert(isa(mask,'uint8') && isequal(size(mask),[512,512]), ...
    'Tesla:CameraMaskFormat','Expected original 512x512 uint8 mask.');
assert(all(mask(:)==0 | mask(:)==1), ...
    'Tesla:CameraMaskFormat','Prediction mask must preserve binary 0/1 labels.');
frame.metadata = metadata;
frame.road_mask = mask == 1;
frame.metric_planning_map = [];
frame.planning_use_valid = false;
frame.note = 'Camera image pixels only. A calibrated ground-plane projection and separate obstacle observations are required before planning.';
end
function value=textEquals(actual,expected)
value=ischar(actual) && isrow(actual) && strcmp(actual,expected);
end
function value=isFalse(actual)
value=islogical(actual) && isscalar(actual) && ~actual;
end
